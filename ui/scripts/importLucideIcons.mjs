// Converts the Lucide icons the map draws into path data for `Path2D`:
//   node ui/scripts/importLucideIcons.mjs <lucide-static package directory>
// Writes ui/src/map/icons/lucideIcons.ts. Lucide is not a dependency; its license is in
// ui/src/map/icons/LICENSE-lucide.txt. To change the icon set, edit ICONS and run this again.
// Core
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ICONS = [
  'file',
  'file-braces',
  'file-text',
  'file-digit',
  'file-x',
  'lock',
  'database',
  'rows-3',
  'scroll-text',
  'mouse-pointer-click',
  'send',
  'navigation',
]
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '../src/map/icons/lucideIcons.ts')

const number = (attributes, name) => Number(attributes[name] ?? 0)

/** One SVG shape as path data; Lucide uses only these elements. */
function pathOf(element, attributes) {
  switch (element) {
    case 'path':
      return attributes.d
    case 'line':
      return `M${attributes.x1} ${attributes.y1}L${attributes.x2} ${attributes.y2}`
    case 'polyline':
    case 'polygon': {
      const points = attributes.points.trim().split(/[\s,]+/)
      const pairs = []
      for (let index = 0; index < points.length; index += 2) pairs.push(`${points[index]} ${points[index + 1]}`)
      return `M${pairs.join('L')}${element === 'polygon' ? 'Z' : ''}`
    }
    case 'circle':
    case 'ellipse': {
      const [cx, cy] = [number(attributes, 'cx'), number(attributes, 'cy')]
      const rx = number(attributes, element === 'circle' ? 'r' : 'rx')
      const ry = number(attributes, element === 'circle' ? 'r' : 'ry')
      return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`
    }
    case 'rect': {
      const [x, y, width, height] = ['x', 'y', 'width', 'height'].map((name) => number(attributes, name))
      const r = Math.min(number(attributes, 'rx') || number(attributes, 'ry'), width / 2, height / 2)
      if (r === 0) return `M${x} ${y}h${width}v${height}h${-width}Z`
      return `M${x + r} ${y}h${width - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${height - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}` +
        `h${-(width - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(height - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`
    }
    default:
      throw new Error(`unsupported SVG element <${element}>`)
  }
}

function paths(svg) {
  const shapes = [...svg.matchAll(/<(path|line|polyline|polygon|circle|ellipse|rect)\b([^>]*?)\/?>/g)]
  return shapes.map(([, element, rest]) => {
    const attributes = Object.fromEntries([...rest.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, name, value]) => [name, value]))
    return pathOf(element, attributes)
  })
}

const [packageDir] = process.argv.slice(2)
if (!packageDir) throw new Error('usage: node ui/scripts/importLucideIcons.mjs <lucide-static package directory>')
const { version } = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'))
const entries = ICONS.map((name) => {
  const data = paths(readFileSync(join(packageDir, 'icons', `${name}.svg`), 'utf8'))
  if (data.length === 0) throw new Error(`${name}: no shapes`)
  return `  '${name}': [\n${data.map((d) => `    '${d}',`).join('\n')}\n  ],`
})
writeFileSync(
  OUTPUT,
  `// Generated by ui/scripts/importLucideIcons.mjs from lucide-static ${version}; do not edit by hand.
// Lucide icons: ISC License, Copyright (c) 2026 Lucide Icons and Contributors; \`database\`, \`lock\` and
// \`navigation\` are derived from Feather: MIT License, Copyright (c) 2013-present Cole Bemis. Full texts in
// ./LICENSE-lucide.txt. Each icon is drawn on a 24 × 24 grid with a 2-unit round stroke and no fill.

export const LUCIDE_VERSION = '${version}'

export const lucideIcons = {
${entries.join('\n')}
} as const satisfies Record<string, readonly string[]>

export type LucideIcon = keyof typeof lucideIcons
`,
)
console.log(`wrote ${ICONS.length} icons from lucide-static ${version} to ${OUTPUT}`)
